SCHEMAS = {"IFC4": IFC4, "IFC4X3_ADD2": IFC4X3_ADD2}

def check_class(name: str, schema: str = "IFC4") -> str:
    """Sinf nomi (registrdan qat'i nazar) sxemada bo'lsa to'g'ri yozilishini qaytaradi, aks holda ValueError."""
    classes = SCHEMAS.get((schema or "IFC4").upper().replace("IFC4X3", "IFC4X3_ADD2") if not (schema or "").upper().endswith("_ADD2") else schema.upper(), IFC4)
    lookup = {c.lower(): c for c in classes}
    c = lookup.get((name or "").strip().lower())
    if c is None:
        raise ValueError(f"IFC sinfi noto'g'ri yoki {schema} sxemasida yo'q: {name}")
    return c


def from_freecad_type(ifc_type: str, schema: str = "IFC4") -> str:
    """Bo'shliqli IFC tur yorlig'i («Pipe Segment», eski modellarda uchraydi) → «IfcPipeSegment», sxemaga nisbatan
    tekshirilgan. Nomi server API muvofiqligi uchun saqlangan."""
    return check_class("Ifc" + (ifc_type or "").replace(" ", ""), schema)
